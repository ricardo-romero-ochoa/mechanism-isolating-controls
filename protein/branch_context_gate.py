"""Gate 1 protein test: does the model use the *paired branch context*?

This is the gate-approved replacement for the legacy aggregate shuffle in ``run_phase2.py``.
The old analysis first collapsed branches into counts for (site, ancestral state, destination) and
then shuffled backgrounds. A focal-state-preserving shuffle after that aggregation is an identity,
so an unrestricted shuffle can change fit only by changing which ancestral-state stratum receives
which backgrounds. It is therefore not a clean test of branch-context pairing.

Here the unit is an observed substitution event on a reconstructed branch. Conditional on a
substitution having occurred at site i from ancestral state a, the response is the destination state.
For each event we score all 19 possible destinations using the *actual parent background*. A null
exchangeability q(a->b) is estimated leave-one-site-out. Context is then permuted by drawing a donor
background from branches with the same site i and ancestral state a, which destroys only the pairing
between the event and the non-focal background.

Required files are generated by the gate-ready protein pipeline:
  protein/bg_<TAG>.npz            (run prep_bg.py; must contain Ps and Cs)
  protein/pg/mf_<TAG>.npz         (mean-field J,h; run run_phase2.py)
  protein/pg/plm_out.npz          (TEM1 pseudo-likelihood; run run_phase2.py)
  protein/esmM_<TAG>.npz          (masked ESM-2 scores; run esm_masked.py)

Examples:
  cd protein
  python branch_context_gate.py TEM1 mf 100
  python branch_context_gate.py TEM1 plm 100
  python branch_context_gate.py TEM1 esmM 100
  python branch_context_gate.py HIS7 mf 100
  python branch_context_gate.py HIS7 esmM 100
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import minimize
from scipy.special import logsumexp

sys.path.insert(0, os.getcwd())
from p4lib import background_energies, profile, weights  # noqa: E402

AA = 20
PC = 0.5


def leave_site_out_q(Ps: np.ndarray, Cs: np.ndarray, pc: float = PC) -> np.ndarray:
    """q[i,a,b] estimated from substitutions at all sites except i."""
    B, L = Ps.shape
    Nc = np.zeros((L, AA, AA), dtype=np.int64)
    br, si = np.nonzero((Ps != Cs) & (Ps < AA) & (Cs < AA))
    np.add.at(Nc, (si, Ps[br, si], Cs[br, si]), 1)
    total = Nc.sum(0).astype(float)
    q = total[None, :, :] - Nc.astype(float) + pc
    for i in range(L):
        np.fill_diagonal(q[i], 0.0)
    den = q.sum(2, keepdims=True)
    q /= np.maximum(den, 1e-300)
    return q


def event_table(Ps: np.ndarray, Cs: np.ndarray):
    """Observed substitution events: branch, site, ancestral state, destination state."""
    br, si = np.nonzero((Ps != Cs) & (Ps < AA) & (Cs < AA))
    a = Ps[br, si].astype(np.int64)
    c = Cs[br, si].astype(np.int64)
    return br.astype(np.int64), si.astype(np.int64), a, c


def nearest_event_profiles(train: np.ndarray, Ps: np.ndarray, br: np.ndarray, si: np.ndarray,
                           a: np.ndarray, k: int = 50, pseudo: float = 0.01,
                           block: int = 80) -> np.ndarray:
    """Destination log-frequency differences from k nearest training sequences for each event.

    Returns E x 20 values log f_i(d | nearest context) - log f_i(a | nearest context).
    """
    train = np.asarray(train, np.int64)
    Ps = np.asarray(Ps, np.int64)
    ntr, L = train.shape
    B = Ps.shape[0]
    q = 21
    Xt = np.zeros((ntr, L * q), np.float32)
    Xt[np.arange(ntr)[:, None], np.arange(L)[None, :] * q + train] = 1.0
    Xp = np.zeros((B, L * q), np.float32)
    Xp[np.arange(B)[:, None], np.arange(L)[None, :] * q + Ps] = 1.0
    out = np.zeros((len(br), AA), np.float32)
    order = np.argsort(br)
    brs = br[order]
    for s in range(0, B, block):
        e = min(s + block, B)
        left = np.searchsorted(brs, s, side="left")
        right = np.searchsorted(brs, e, side="left")
        if left == right:
            continue
        sim = Xp[s:e] @ Xt.T
        kk = min(k, max(1, ntr - 1))
        nb = np.argpartition(-sim, kk - 1, axis=1)[:, :kk]
        ev_ord = order[left:right]
        for idx in ev_ord:
            b = int(br[idx]); i = int(si[idx]); anc = int(a[idx])
            vals = train[nb[b - s], i]
            cnt = np.bincount(vals[vals < AA], minlength=AA).astype(float)
            lp = np.log((cnt + pseudo) / (cnt.sum() + pseudo * AA))
            out[idx] = lp - lp[anc]
    return out


def fit_conditional(logq: np.ndarray, obs: np.ndarray, anc: np.ndarray,
                    predictors: list[np.ndarray], grad_tol: float = 1e-7):
    """Conditional multinomial fit over 19 destinations with a numerical certificate.

    The statistical endpoint is unchanged.  Optimisation is performed on *mean* negative
    log-likelihood (rather than its event-count-scaled sum) so the gradient tolerance has the
    same meaning across families.  BFGS is the prespecified first solver; L-BFGS-B is used only
    when BFGS fails the outcome-independent gradient certificate.  A fit is called converged
    from the analytic gradient, not merely from SciPy's solver-success flag.
    """
    E = len(obs)
    rows = np.arange(E)
    valid = np.ones((E, AA), dtype=bool)
    valid[rows, anc] = False

    base = np.array(logq, dtype=float, copy=True)
    base[~valid] = -np.inf
    Xs = [np.asarray(x, float) for x in predictors]
    if not Xs:
        lse = logsumexp(base, axis=1)
        ll = float(np.sum(base[rows, obs] - lse))
        return {"ll": ll, "coef": [], "converged": True, "nit": 0,
                "optimizer": "closed_form_offset", "scipy_success": True,
                "gradient_inf_per_event": 0.0, "gradient_tolerance": float(grad_tol),
                "message": "no fitted coefficients"}

    def mean_fun_grad(beta):
        z = base.copy()
        for b, x in zip(beta, Xs):
            z += b * x
        lse = logsumexp(z, axis=1)
        ll = np.sum(z[rows, obs] - lse)
        pr = np.exp(z - lse[:, None])
        pr[~valid] = 0.0
        grad_ll = np.array([
            np.sum(x[rows, obs] - np.sum(pr * x, axis=1)) for x in Xs
        ], dtype=float)
        return -float(ll) / max(E, 1), -grad_ll / max(E, 1)

    def pack(opt, method):
        f, g = mean_fun_grad(opt.x)
        ginf = float(np.max(np.abs(g))) if len(g) else 0.0
        finite = bool(np.isfinite(f) and np.all(np.isfinite(opt.x)) and np.isfinite(ginf))
        certified = bool(finite and ginf <= grad_tol)
        return {
            "ll": -float(f) * E,
            "coef": [float(x) for x in opt.x],
            "converged": certified,
            "nit": int(getattr(opt, "nit", 0)),
            "optimizer": method,
            "scipy_success": bool(getattr(opt, "success", False)),
            "gradient_inf_per_event": ginf,
            "gradient_tolerance": float(grad_tol),
            "message": str(getattr(opt, "message", "")),
        }

    x0 = np.zeros(len(Xs), dtype=float)
    opt1 = minimize(lambda b: mean_fun_grad(b), x0, jac=True, method="BFGS",
                    options={"gtol": 1e-9, "maxiter": 1000})
    r1 = pack(opt1, "BFGS_meanNLL")
    if r1["converged"]:
        return r1

    # Deterministic numerical rescue only; the model, predictors and endpoint are unchanged.
    opt2 = minimize(lambda b: mean_fun_grad(b), np.asarray(opt1.x, float), jac=True,
                    method="L-BFGS-B",
                    options={"gtol": 1e-10, "ftol": 1e-15, "maxiter": 2000,
                             "maxls": 50})
    r2 = pack(opt2, "L-BFGS-B_meanNLL_after_BFGS")
    r2["primary_solver"] = r1
    return r2


def donor_branches(Ps: np.ndarray, br: np.ndarray, si: np.ndarray, a: np.ndarray,
                   rng: np.random.Generator) -> np.ndarray:
    """Permute the *observed event contexts* within each (site, ancestral-state) stratum.

    This preserves the exact set of contexts, the site, the focal ancestral state, and the number of
    events in every stratum. Only the pairing between an observed destination and its non-focal
    background is destroyed. Singleton strata are necessarily unchanged.
    """
    donor = br.copy()
    key = si.astype(np.int64) * AA + a.astype(np.int64)
    for k0 in np.unique(key):
        ev = np.flatnonzero(key == k0)
        if len(ev) > 1:
            donor[ev] = rng.permutation(br[ev])
    return donor


def model_scores(tag: str, model_kind: str, d):
    Ps = d["Ps"].astype(np.int64)
    train = d["train"].astype(np.int64)
    if model_kind == "mf":
        z = np.load(f"pg/mf_{tag}.npz")
        J, h = z["J"], z["h"]
        U = background_energies(J, h, Ps)
        return U, h, "statistical-energy"
    if model_kind == "plm":
        if tag != "TEM1":
            raise ValueError("pseudo-likelihood gate is currently available only for TEM1")
        z = np.load("pg/plm_out.npz")
        J, h = z["J"], z["h"]
        U = background_energies(J, h, Ps)
        return U, h, "statistical-energy"
    if model_kind == "esmM":
        z = np.load(f"esmM_{tag}.npz")
        logp = z["logp"].astype(np.float64)
        bn = d["branch_node"].astype(np.int64)
        U = np.ascontiguousarray(logp[bn].transpose(1, 2, 0))
        # Reuse the already-frozen training-profile field from the MF fit.  This is
        # mathematically the same dh baseline previously obtained by recomputing
        # weights(train)+profile(train), but avoids an O(N^2) reweighting for large
        # primary families (notably KKA2).  The context predictor remains ESM-2.
        mf = np.load(f"pg/mf_{tag}.npz")
        h = mf["h"].astype(np.float64)
        if h.shape != (Ps.shape[1], AA):
            raise RuntimeError(f"{tag}: frozen MF profile-field shape {h.shape} != {(Ps.shape[1], AA)}")
        return U, h, str(z["model"][0]) + " | dh=frozen-training-profile"
    raise ValueError(f"unknown model kind {model_kind!r}")


def run(tag: str, model_kind: str, n_perm: int = 100, seed: int = 0, k: int = 50):
    d = np.load(f"bg_{tag}.npz")
    if "Cs" not in d.files:
        raise RuntimeError(
            f"bg_{tag}.npz predates Gate 1 and has no child-state matrix Cs; rerun prep_bg.py")
    Ps, Cs = d["Ps"].astype(np.int64), d["Cs"].astype(np.int64)
    br, si, anc, obs = event_table(Ps, Cs)
    ci_median = None
    ci_below_01 = None
    if "clade_seq" in d.files:
        S = d["clade_seq"].astype(np.int64)
        Ni = np.zeros(Ps.shape[1], dtype=int)
        _, ev_i = np.nonzero((Ps != Cs) & (Ps < AA) & (Cs < AA))
        np.add.at(Ni, ev_i, 1)
        nst = np.array([len(np.unique(S[:, i][S[:, i] < AA])) for i in range(S.shape[1])])
        ci = np.where(Ni > 0, (nst - 1) / np.maximum(Ni, 1), np.nan)
        ci_median = float(np.nanmedian(ci))
        ci_below_01 = float(np.nanmean(ci[~np.isnan(ci)] < 0.1))
    key = si.astype(np.int64) * AA + anc.astype(np.int64)
    _, inv, cnt = np.unique(key, return_inverse=True, return_counts=True)
    permutable = cnt[inv] > 1
    q = leave_site_out_q(Ps, Cs)
    logq = np.log(np.maximum(q[si, anc, :], 1e-300))
    U, h, model_name = model_scores(tag, model_kind, d)

    rows = np.arange(len(obs))
    dctx = U[si, :, br] - U[si, anc, br][:, None]
    dh = h[si, :] - h[si, anc][:, None]
    dsub = nearest_event_profiles(d["train"], Ps, br, si, anc, k=k)

    fit_q = fit_conditional(logq, obs, anc, [])
    fit_dh = fit_conditional(logq, obs, anc, [dh])
    fit_true = fit_conditional(logq, obs, anc, [dh, dctx])
    fit_sub = fit_conditional(logq, obs, anc, [dh, dsub])
    fit_sub_ctx = fit_conditional(logq, obs, anc, [dh, dsub, dctx])

    # Primary permutation statistic is frozen on all observed events.  A secondary sensitivity
    # refits on permutable events only, because singleton (site, ancestor) strata cannot change
    # under the pairing null and can otherwise dilute the operational contrast.
    pm = permutable
    fit_dh_pm = fit_true_pm = None
    if int(pm.sum()) >= 2:
        fit_dh_pm = fit_conditional(logq[pm], obs[pm], anc[pm], [dh[pm]])
        fit_true_pm = fit_conditional(logq[pm], obs[pm], anc[pm], [dh[pm], dctx[pm]])

    rng = np.random.default_rng(seed)
    perm_ll = []
    perm_ll_pm = []
    perm_fit_audit = []
    perm_fit_pm_audit = []
    n_perm_sensitivity = min(int(n_perm), 100)
    for ip in range(n_perm):
        donor = donor_branches(Ps, br, si, anc, rng)
        dp = U[si, :, donor] - U[si, anc, donor][:, None]
        fp = fit_conditional(logq, obs, anc, [dh, dp])
        perm_ll.append(fp["ll"])
        perm_fit_audit.append(fp)
        if fit_dh_pm is not None and ip < n_perm_sensitivity:
            fppm = fit_conditional(logq[pm], obs[pm], anc[pm], [dh[pm], dp[pm]])
            perm_ll_pm.append(fppm["ll"])
            perm_fit_pm_audit.append(fppm)
    perm_ll = np.asarray(perm_ll, float)

    true_gain = fit_true["ll"] - fit_dh["ll"]
    perm_gain = perm_ll - fit_dh["ll"]
    sd = float(perm_gain.std(ddof=1)) if len(perm_gain) > 1 else 0.0
    pmu = float(perm_gain.mean())
    if sd:
        z = (true_gain - pmu) / sd
    elif true_gain > pmu:
        z = float("inf")
    elif true_gain < pmu:
        z = float("-inf")
    else:
        z = 0.0
    empirical_p = float((1 + np.sum(perm_gain >= true_gain)) / (len(perm_gain) + 1))
    pq = np.quantile(perm_gain, [0.025, 0.5, 0.975]) if len(perm_gain) else np.array([np.nan]*3)
    pct_lost = (100.0 * (true_gain - float(perm_gain.mean())) / true_gain
                if abs(true_gain) > 1e-12 else float("nan"))
    added_over_sub = fit_sub_ctx["ll"] - fit_sub["ll"]

    pm_sensitivity = None
    if fit_dh_pm is not None and len(perm_ll_pm):
        perm_ll_pm = np.asarray(perm_ll_pm, float)
        tg = fit_true_pm["ll"] - fit_dh_pm["ll"]
        pg = perm_ll_pm - fit_dh_pm["ll"]
        psd = float(pg.std(ddof=1)) if len(pg) > 1 else 0.0
        pgm = float(pg.mean())
        if psd:
            pz = (tg - pgm) / psd
        elif tg > pgm:
            pz = float("inf")
        elif tg < pgm:
            pz = float("-inf")
        else:
            pz = 0.0
        pp = float((1 + np.sum(pg >= tg)) / (len(pg) + 1))
        pm_sensitivity = {
            "n_events": int(pm.sum()),
            "n_perm": int(len(pg)),
            "context_gain_ll": float(tg),
            "permuted_context_gain_mean_ll": float(pg.mean()),
            "permuted_context_gain_sd_ll": psd,
            "context_pairing_z": float(pz),
            "empirical_one_sided_p": pp,
            "pairing_effect_z2": bool(tg > pg.mean() and pz >= 2.0),
        }

    core_fit_map = {"q": fit_q, "q+dh": fit_dh, "q+dh+context": fit_true,
                    "q+dh+nearest": fit_sub, "q+dh+nearest+context": fit_sub_ctx}
    core_grad = [float(x.get("gradient_inf_per_event", 0.0)) for x in core_fit_map.values()]
    perm_grad = [float(x.get("gradient_inf_per_event", np.inf)) for x in perm_fit_audit]
    perm_pm_grad = [float(x.get("gradient_inf_per_event", np.inf)) for x in perm_fit_pm_audit]
    optimizer_audit = {
        "audit_version": "G1C_OPTIMIZER_AUDIT_v1.2_POST_OUTCOME_NUMERICAL_ONLY",
        "endpoint_changed": False,
        "mean_nll_scaling": True,
        "gradient_certificate_per_event": 1e-7,
        "core_all_converged": bool(all(x.get("converged", False) for x in core_fit_map.values())),
        "core_max_gradient_inf_per_event": float(max(core_grad) if core_grad else 0.0),
        "primary_permutation_converged": int(sum(bool(x.get("converged", False)) for x in perm_fit_audit)),
        "primary_permutation_total": int(len(perm_fit_audit)),
        "primary_permutation_max_gradient_inf_per_event": float(max(perm_grad) if perm_grad else 0.0),
        "sensitivity_permutation_converged": int(sum(bool(x.get("converged", False)) for x in perm_fit_pm_audit)),
        "sensitivity_permutation_total": int(len(perm_fit_pm_audit)),
        "sensitivity_permutation_max_gradient_inf_per_event": float(max(perm_pm_grad) if perm_pm_grad else 0.0),
        "fallback_used_core": int(sum(str(x.get("optimizer", "")).startswith("L-BFGS-B") for x in core_fit_map.values())),
        "fallback_used_primary_permutations": int(sum(str(x.get("optimizer", "")).startswith("L-BFGS-B") for x in perm_fit_audit)),
        "fallback_used_sensitivity_permutations": int(sum(str(x.get("optimizer", "")).startswith("L-BFGS-B") for x in perm_fit_pm_audit)),
    }

    out = {
        "gate": "branch-level focal-state-preserving context test",
        "endpoint_version": "G1C_EVENT_CONTEXT_v1.1_PRE_OUTCOME",
        "numerical_audit_version": "G1C_OPTIMIZER_AUDIT_v1.2_POST_OUTCOME_NUMERICAL_ONLY",
        "tag": tag,
        "model_kind": model_kind,
        "model": model_name,
        "n_events": int(len(obs)),
        "n_permutable_events": int(permutable.sum()),
        "permutable_event_fraction": float(permutable.mean()) if len(permutable) else 0.0,
        "n_branches": int(Ps.shape[0]),
        "n_sites": int(Ps.shape[1]),
        "ancestral_reconstruction_CI_median": ci_median,
        "ancestral_reconstruction_frac_CI_below_0p1": ci_below_01,
        "ancestral_reconstruction_gate_caution": bool(ci_median is None or ci_median < 0.2),
        "null_exchangeability": "leave-one-site-out",
        "nearest_profile_k": int(k),
        "n_perm": int(n_perm),
        "fits": core_fit_map,
        "optimizer_audit": optimizer_audit,
        "context_gain_ll": float(true_gain),
        "permuted_context_gain_mean_ll": float(perm_gain.mean()),
        "permuted_context_gain_sd_ll": sd,
        "context_pairing_z": float(z),
        "empirical_one_sided_p": empirical_p,
        "permuted_context_gain_quantiles_2p5_50_97p5": [float(x) for x in pq],
        "context_fit_lost_pct": float(pct_lost),
        "context_added_over_nearest_ll": float(added_over_sub),
        "context_added_over_nearest_LR": float(2.0 * added_over_sub),
        "pairing_effect_z2": bool(true_gain > perm_gain.mean() and z >= 2.0),
        "adds_over_nearest_positive": bool(added_over_sub > 0.0),
        "adds_over_nearest_LR_3p84": bool(2.0 * added_over_sub >= 3.84),
        "permutable_event_only_sensitivity": pm_sensitivity,
    }
    out["mechanistic_support_primary_rule"] = bool(
        out["pairing_effect_z2"] and out["adds_over_nearest_positive"]
    )

    # Keep technical gate execution separate from the biological verdict. A model that shows no
    # event-specific context effect is a scientifically informative negative result, not a failed
    # computation. Primary-analysis interpretation additionally requires >=100 permutations and
    # ancestral reconstruction at or above the frozen CI threshold.
    all_core_fits = [fit_q, fit_dh, fit_true, fit_sub, fit_sub_ctx]
    all_primary_perm_converged = bool(len(perm_fit_audit) == n_perm and
                                      all(x.get("converged", False) for x in perm_fit_audit))
    all_sens_perm_converged = bool(len(perm_fit_pm_audit) == len(perm_ll_pm) and
                                   all(x.get("converged", False) for x in perm_fit_pm_audit))
    if n_perm < 100:
        execution_grade = "EXPLORATORY_LT100_PERMUTATIONS"
    elif not all(bool(x.get("converged", False)) for x in all_core_fits):
        execution_grade = "HOLD_OPTIMIZER_NONCONVERGENCE_CORE"
    elif not all_primary_perm_converged:
        execution_grade = "HOLD_OPTIMIZER_NONCONVERGENCE_PRIMARY_PERMUTATIONS"
    elif not all_sens_perm_converged:
        execution_grade = "HOLD_OPTIMIZER_NONCONVERGENCE_SENSITIVITY_PERMUTATIONS"
    elif ci_median is None:
        execution_grade = "HOLD_RECONSTRUCTION_CI_UNAVAILABLE"
    elif ci_median < 0.20:
        execution_grade = "HOLD_RECONSTRUCTION_CI_LT_0p20"
    else:
        execution_grade = "SUBMISSION_GRADE"

    if out["mechanistic_support_primary_rule"]:
        biological_verdict = "EVENT_SPECIFIC_CONTEXT_MECHANISTIC_SUPPORT"
    elif out["pairing_effect_z2"] and not out["adds_over_nearest_positive"]:
        biological_verdict = "PAIRING_SIGNAL_NOT_ADDITIVE_OVER_NEAREST"
    else:
        biological_verdict = "NO_EVENT_SPECIFIC_CONTEXT_SUPPORT_AT_FROZEN_RULE"

    out["execution_grade"] = execution_grade
    out["biological_verdict"] = biological_verdict
    out["submission_grade_pairing_signal"] = bool(
        execution_grade == "SUBMISSION_GRADE" and out["mechanistic_support_primary_rule"]
    )
    out["submission_grade_negative_pairing_result"] = bool(
        execution_grade == "SUBMISSION_GRADE" and not out["mechanistic_support_primary_rule"]
    )
    return out


def main():
    tag = sys.argv[1] if len(sys.argv) > 1 else "TEM1"
    kind = sys.argv[2] if len(sys.argv) > 2 else "mf"
    n_perm = int(sys.argv[3]) if len(sys.argv) > 3 else 100
    suffix = sys.argv[4] if len(sys.argv) > 4 else ""
    suffix = ("_" + suffix) if suffix and not suffix.startswith("_") else suffix
    out = run(tag, kind, n_perm=n_perm)
    Path("../results").mkdir(exist_ok=True)
    dest = Path("../results") / f"gate1_branch_{tag}_{kind}{suffix}.json"
    dest.write_text(json.dumps(out, indent=2) + "\n")
    print(json.dumps(out, indent=2))
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
